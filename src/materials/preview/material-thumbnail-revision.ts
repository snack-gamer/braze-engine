import type { Material } from "../domain/material";

/** Identifies every authored surface value that can change a rendered thumbnail. */
export function materialThumbnailRevision(material: Material): string {
  return JSON.stringify([
    material.color,
    material.roughness,
    material.metalness,
    material.specularIntensity,
    material.clearcoat,
    material.clearcoatRoughness,
    material.ior,
    material.transmission,
    material.emissive,
    material.emissiveIntensity,
    material.opacity,
    material.normalScale,
    material.bumpScale,
    material.aoIntensity,
    material.alphaCutoff,
    material.envMapIntensity,
    material.thickness,
    material.sheen,
    material.sheenRoughness,
    material.sheenColor,
    material.side,
    material.wireframe,
    material.baseColorTextureUrl,
    material.baseColorTextureFlipY,
    material.normalTextureUrl,
    material.normalTextureFlipY,
    material.bumpTextureUrl,
    material.bumpTextureFlipY,
    material.roughnessTextureUrl,
    material.roughnessTextureFlipY,
    material.metalnessTextureUrl,
    material.metalnessTextureFlipY,
    material.emissiveTextureUrl,
    material.emissiveTextureFlipY,
    material.alphaTextureUrl,
    material.alphaTextureFlipY,
    material.aoTextureUrl,
    material.aoTextureFlipY,
  ]);
}
