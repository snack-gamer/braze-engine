import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 980 } });
const errors = [];
page.on('pageerror', (err) => errors.push(`pageerror: ${err.message}`));
page.on('console', (msg) => { if (msg.type() === 'error') errors.push(`console.error: ${msg.text()}`); });
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await page.waitForSelector('.three-host canvas', { timeout: 8000 });
await page.waitForSelector('.scene-label-layer', { timeout: 3000 });
await page.waitForTimeout(1500);
const labelCount = await page.$$eval('.scene-label', (els) => els.length);
console.log('labels rendered:', labelCount);
await page.screenshot({ path: '/tmp/tgan_labels.png', fullPage: false });
console.log('errors:', errors.filter((e) => !e.includes('WebSocket')).length);
await browser.close();
